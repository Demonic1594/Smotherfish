"""Export a trained MLP to src/smother_net.h (normalisation folded in)."""
import torch, numpy as np, sys
ck = torch.load(sys.argv[1], weights_only=False); sd_ = ck["m"]; mu, sd = ck["mu"], ck["sd"]
W1 = sd_["0.weight"].numpy().astype(np.float64); b1 = sd_["0.bias"].numpy().astype(np.float64)
W2 = sd_["2.weight"].numpy()[0]; b2 = float(sd_["2.bias"].numpy()[0])
H, N = W1.shape
W1f = W1.copy(); W1f[:, :17] = W1[:, :17] / sd; b1f = b1 - (W1[:, :17] * (mu / sd)).sum(1)
# store transposed: per input a row of H weights (sparse accumulation)
def arr(a): return ",".join(f"{x:.6g}f" for x in a)
rows = ",\n    ".join("{" + arr(W1f[:, i]) + "}" for i in range(N))
open(sys.argv[2], "w").write(f"""// Generated by notes/scripts/nn_export.py from {sys.argv[3]}. Do not edit.
// Knight (classic) smother network: {N} inputs -> {H} ReLU -> 1 logit.
#ifndef SMOTHER_NET_H_INCLUDED
#define SMOTHER_NET_H_INCLUDED
namespace Stockfish::Smother::Net {{
constexpr int Inputs = {N}, Hidden = {H};
constexpr float W1[Inputs][Hidden] = {{
    {rows}}};
constexpr float B1[Hidden] = {{{arr(b1f)}}};
constexpr float W2[Hidden] = {{{arr(W2)}}};
constexpr float B2 = {b2:.6g}f;
}}
#endif
""")
print("H", H, "N", N)
